// Versioned prompts (ADR-008 §8). Every declared model task is locked as `<name>@<version>` →
// sha256 of what the model is given and must return: the composed system prompt (firm preamble +
// department preamble + task prompt), the schema fingerprint (shape, enums, caps, grounded
// markers) and the tier hint (difficulty, highStakes, the code-default model ids). Changing any of
// them without bumping the version fails `scripts/verify-prompts.ts`; a new version is missing from
// the lock until `--update` adds it — run deliberately together with that agent's accuracy gate.
// The lock is append-only: an existing `<name>@<version>` never changes hash and old versions stay
// as history, so a version number can never be reused for a different prompt. Pure.
import { createHash } from "node:crypto";
import type { FirmService } from "@prisma/client";
import { DEFAULT_MODELS } from "@/lib/ai/config";
import { composeSystemPrompt, taskLabel, type AnyTaskSpec, type ScopedAgentLike } from "./scope";
import { schemaFingerprint } from "./schema";

export const PROMPT_LOCK_FILE = "prompts.lock.json";
export const PROMPT_LOCK_NOTE =
  "Generated by scripts/verify-prompts.ts --update (ADR-008). Each entry is <agent>.<task>@<version> -> sha256(system prompt + schema shape + tier hint). Never edit by hand; bump the task version instead.";

export type PromptLock = { lockVersion: 1; note: string; prompts: Record<string, string> };
export type LockedTask = { agent: string; label: string; hash: string };

/** sha256 of the material the model sees and must return for one task of one department. */
export function promptHash(department: FirmService, task: AnyTaskSpec): string {
  const material = {
    system: composeSystemPrompt(department, task),
    schema: schemaFingerprint(task.schema),
    tier: { difficulty: task.difficulty ?? null, highStakes: task.highStakes === true, models: DEFAULT_MODELS },
  };
  return createHash("sha256").update(JSON.stringify(material)).digest("hex");
}

/** Every task of every scoped agent, with its current hash (agents without a scope have none). */
export function currentPrompts(agents: Readonly<Record<string, ScopedAgentLike>>): LockedTask[] {
  const out: LockedTask[] = [];
  for (const def of Object.values(agents)) {
    if (!def.scope) continue;
    for (const t of def.scope.tasks) out.push({ agent: def.key, label: taskLabel(t), hash: promptHash(def.scope.department, t) });
  }
  return out.sort((a, b) => a.label.localeCompare(b.label));
}

export const emptyPromptLock = (): PromptLock => ({ lockVersion: 1, note: PROMPT_LOCK_NOTE, prompts: {} });

export function parsePromptLock(text: string): PromptLock {
  const raw = JSON.parse(text) as Partial<PromptLock>;
  if (raw.lockVersion !== 1 || typeof raw.prompts !== "object" || raw.prompts === null) throw new Error(`${PROMPT_LOCK_FILE}: expected { lockVersion: 1, prompts: { "<task>@<version>": "<sha256>" } }`);
  for (const [k, v] of Object.entries(raw.prompts)) {
    if (!/^[a-z0-9_-]+\.[^@\s]+@\d+$/.test(k) || typeof v !== "string" || !/^[0-9a-f]{64}$/.test(v)) throw new Error(`${PROMPT_LOCK_FILE}: bad entry ${JSON.stringify(k)}`);
  }
  return { lockVersion: 1, note: typeof raw.note === "string" ? raw.note : PROMPT_LOCK_NOTE, prompts: { ...raw.prompts } };
}

/** Stable text (sorted keys, trailing newline) so lock diffs read cleanly in review. */
export function serializePromptLock(lock: PromptLock): string {
  const prompts = Object.fromEntries(Object.keys(lock.prompts).sort().map((k) => [k, lock.prompts[k]]));
  return `${JSON.stringify({ lockVersion: 1, note: lock.note || PROMPT_LOCK_NOTE, prompts }, null, 2)}\n`;
}

export type LockCheck = { ok: boolean; changed: string[]; missing: string[]; duplicates: string[]; problems: string[] };

/** Compare the code's tasks with the lock. */
export function verifyPromptLock(lock: PromptLock, current: LockedTask[]): LockCheck {
  const changed: string[] = [];
  const missing: string[] = [];
  const duplicates: string[] = [];
  const problems: string[] = [];
  const seen = new Map<string, string>();
  for (const t of current) {
    const prev = seen.get(t.label);
    if (prev !== undefined && prev !== t.hash) {
      duplicates.push(t.label);
      problems.push(`${t.label}: declared twice with different prompts (agent ${t.agent})`);
    }
    seen.set(t.label, t.hash);
    const locked = lock.prompts[t.label];
    if (locked === undefined) {
      missing.push(t.label);
      problems.push(`${t.label}: not in ${PROMPT_LOCK_FILE} — run the ${t.agent} accuracy gate, then npx tsx scripts/verify-prompts.ts --update`);
    } else if (locked !== t.hash) {
      changed.push(t.label);
      problems.push(
        `${t.label}: prompt, schema or tier hint changed without a version bump (locked ${locked.slice(0, 12)}…, now ${t.hash.slice(0, 12)}…) — bump the task version and re-run the ${t.agent} accuracy gate`,
      );
    }
  }
  return { ok: problems.length === 0, changed, missing, duplicates, problems };
}

/** Add missing entries. An existing entry whose hash differs is refused (bump the version). Nothing is removed. */
export function updatePromptLock(lock: PromptLock, current: LockedTask[]): { lock: PromptLock; added: string[]; refused: string[] } {
  const prompts = { ...lock.prompts };
  const added: string[] = [];
  const refused: string[] = [];
  for (const t of current) {
    const locked = prompts[t.label];
    if (locked === undefined) {
      prompts[t.label] = t.hash;
      added.push(t.label);
    } else if (locked !== t.hash && !refused.includes(t.label)) refused.push(t.label);
  }
  return { lock: { ...lock, prompts }, added, refused };
}
